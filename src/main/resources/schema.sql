-- Session principal names are user account keys supplied by Spring Security.
-- A quoted function body keeps this script compatible with Spring SQL initialization.
CREATE OR REPLACE FUNCTION stamp_session_audit() RETURNS TRIGGER
LANGUAGE plpgsql AS '
DECLARE
    actor BIGINT;
BEGIN
    IF TG_TABLE_NAME = ''spring_session'' THEN
        actor := NEW.PRINCIPAL_NAME::BIGINT;
    ELSE
        SELECT PRINCIPAL_NAME::BIGINT INTO actor
        FROM SPRING_SESSION WHERE PRIMARY_ID = NEW.SESSION_PRIMARY_ID;
    END IF;
    IF TG_OP = ''INSERT'' THEN
        NEW.created_by := actor;
    ELSE
        NEW.created_by := OLD.created_by;
    END IF;
    NEW.updated_by := actor;
    RETURN NEW;
END;
';

DROP TRIGGER IF EXISTS spring_session_audit ON SPRING_SESSION;
CREATE TRIGGER spring_session_audit BEFORE INSERT OR UPDATE ON SPRING_SESSION
    FOR EACH ROW EXECUTE FUNCTION stamp_session_audit();

DROP TRIGGER IF EXISTS spring_session_attributes_audit ON SPRING_SESSION_ATTRIBUTES;
CREATE TRIGGER spring_session_attributes_audit BEFORE INSERT OR UPDATE ON SPRING_SESSION_ATTRIBUTES
    FOR EACH ROW EXECUTE FUNCTION stamp_session_audit();

